"""Writes frontend/src/fitkat/swap-data.js: what the app needs to pick a stand-in for an exercise her place
has no kit for (fitkat/place-swaps.js suggestSwaps).

    python3 scripts/fitkat/swaps/export.py                 # writes the file
    python3 scripts/fitkat/swaps/export.py --check         # fails if the file on disk is out of date

Two things go in.

MOVE: the movement of an exercise, read from its name by the same rules the limits ladders use
(scripts/fitkat/limits/moves.py). A stand-in of the same movement comes before one that only shares the
muscle. Until 22 Nov the app went by the words two names share, so a pushdown and a kickback, which share
none, could never count as close.

POS: for a triceps extension, where the upper arm is: by the side (pushdown, kickback), overhead, or lying.
All three are "triceps extension", and the difference matters: with a cable pushdown and no cable, a
kickback is the natural stand-in, and a lying or overhead extension is not. Read from the name, then
from the written steps where the name does not say. Other movements have no position yet.

PICKS: the reviewed first choices for the exercises of the built-in programmes (picks.json, see README.md).

NEVER: what every reviewer called no stand-in at all for one of those exercises. Never suggested for it.
"""
import contextlib, io, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(HERE, '..', 'limits'))
with contextlib.redirect_stdout(io.StringIO()):
    import moves as V
EX = V.EX
OUT = os.path.join(ROOT, 'frontend', 'src', 'fitkat', 'swap-data.js')
s = lambda p, n: bool(re.search(p, n))


def triceps_position(i):
    """'s' by the side, 'o' overhead, 'l' lying, or None when neither the name nor the steps say."""
    n = EX[i]['name'].lower()
    if s(r'kick.?back|kick back', n): return 's'
    if s(r'lying|skull|supine|decline|nose', n): return 'l'
    if s(r'push.?down|press.?down', n): return 's'
    if s(r'overhead|over head|french|behind|high pulley|incline', n): return 'o'
    text = ' '.join(EX[i].get('instructions') or []).lower() + ' ' + (EX[i].get('description') or '').lower()
    if s(r'\blie\b|\blying\b|on your back', text): return 'l'
    if s(r'overhead|over your head|above your head|behind your head|behind the head', text): return 'o'
    if s(r'close to your sides|at your sides|by your sides|hinge forward|push.?down|press.?down', text): return 's'
    if s(r'seated|standing|kneeling', n): return 'o'      # a seated or standing "triceps extension" is the overhead one
    return None


def build():
    moves, move, pos = [], {}, {}
    for i in sorted(EX):
        m = V.movement(i)
        if not m: continue
        if m not in moves: moves.append(m)
        move[i] = moves.index(m)
        if m == 'triceps extension':
            p = triceps_position(i)
            if p: pos[i] = p
    picks, never = {}, {}
    pf = os.path.join(HERE, 'picks.json')
    if os.path.exists(pf):
        reviewed = json.load(open(pf))
        for name, into in (('picks', picks), ('never', never)):
            for i, ids in reviewed[name].items():
                assert i in EX and all(x in EX for x in ids), i
                if ids: into[i] = ids
        assert not any(set(picks.get(i, [])) & set(never[i]) for i in never)
    js = lambda x: json.dumps(x, ensure_ascii=False, separators=(',', ':'))
    return ('// Generated by scripts/fitkat/swaps/export.py from the catalogue, the movement rules of the limits ladders and\n'
            '// scripts/fitkat/swaps/picks.json. Do not edit by hand.\n//\n'
            '// MOVE[exerciseId] indexes MOVES: the movement an exercise is, where its name says so.\n'
            "// POS[exerciseId]: for a triceps extension, where the upper arm is: 's' by the side, 'o' overhead, 'l' lying.\n"
            '// PICKS[exerciseId]: reviewed first choices to stand in for it, best first, across every kind of kit.\n'
            '// NEVER[exerciseId]: what every reviewer called no stand-in for it.\n'
            'export const MOVES = ' + js(moves) + '\n'
            'export const MOVE = ' + js(move) + '\n'
            'export const POS = ' + js(pos) + '\n'
            'export const PICKS = ' + js(picks) + '\n'
            'export const NEVER = ' + js(never) + '\n'), (len(move), len(pos), sum(len(v) for v in picks.values()), sum(len(v) for v in never.values()))


if __name__ == '__main__':
    text, counts = build()
    if '--check' in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text: sys.exit('swap-data.js is out of date: run scripts/fitkat/swaps/export.py')
        print('swap-data.js is up to date'); sys.exit(0)
    open(OUT, 'w').write(text)
    print('movements %d, positions %d, reviewed picks %d, never %d' % counts, '|', len(text), 'bytes')
