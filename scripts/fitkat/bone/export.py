"""Writes frontend/src/fitkat/bone-data.js from tags.json. Usage: python3 scripts/fitkat/bone/export.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get('OPENGYM_ROOT') or os.path.abspath(os.path.join(HERE, '..', '..', '..'))
tags = json.load(open(os.path.join(HERE, 'tags.json')))
have = lambda i: os.path.exists(os.path.join(ROOT, 'catalogue', 'exercises', i + '.json'))
js = lambda v: json.dumps(v, separators=(',', ':'))
out = os.path.join(ROOT, 'frontend', 'src', 'fitkat', 'bone-data.js')
with open(out, 'w') as f:
    f.write('// Generated by scripts/fitkat/bone/export.py from tags.json. Do not edit by hand.\n')
    f.write('// Which exercises count toward the bone and balance goals. Each was read by several AI models,\n')
    f.write('// not by a clinician (scripts/fitkat/bone/README.md).\n')
    f.write('// BALANCE and POSTURE are exercise ids. IMPACT[id] is 1 low, 2 moderate, 3 high, through the legs.\n')
    f.write('export const BALANCE = ' + js([i for i in tags['balance'] if have(i)]) + '\n')
    f.write('export const POSTURE = ' + js([i for i in tags['posture'] if have(i)]) + '\n')
    f.write('export const IMPACT = ' + js({i: v for i, v in tags['impact'].items() if have(i)}) + '\n')
print('wrote', out)
