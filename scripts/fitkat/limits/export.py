"""Writes frontend/src/fitkat/limits-data.js: which exercises load which area, and what each is offered.

    python3 tag.py <repo root>        # tags.json, from the catalogue
    python3 moves.py                  # the reproduction test against the approved ladders
    python3 export.py <out file>

The app does the rest at run time (fitkat/limits.js): Go easy or Avoid, her place's kit, her other limits.
"""
import json, sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import moves as V

CODE = {'neck': 'n', 'shoulder': 's', 'elbow': 'e', 'wrist': 'w', 'lower back': 'b', 'hip': 'h', 'knee': 'k', 'ankle': 'a'}
whys, lists, flags, touches = [], [], {}, {}
widx, lidx = {}, {}


def why(t):
    if t not in widx: widx[t] = len(whys); whys.append(t)
    return widx[t]


for i in sorted(V.EX):
    t = V.TAGS[i]
    if V.form_check(i): continue
    row = {}
    for area, v in t['limits'].items():
        if v != 2: continue
        m = V.movement(i)
        if m and V.unflagged(i, m, area): continue
        o = V.offers(i, area)
        if o is None or not o['entries']:
            ge, _ = V.fallback(i, area)
            row[CODE[area]] = 'x' if ge == 'Skip it?' else 't' if 'shorter' in ge else 'e'
            continue
        steps = []
        for st in o['entries']:
            if st['kind'] == V.ADJ: steps.append(['a', why(st['whys'][0])])
            else: steps.append(['h' if st['kind'] == V.H else 'r', [[V.BY[n], why(w)] for n, w in zip(st['names'], st['whys'])]])
        key = json.dumps(steps)
        if key not in lidx: lidx[key] = len(lists); lists.append(steps)
        row[CODE[area]] = lidx[key]
    if row: flags[i] = row
    # Takes part without being the point (a hip thrust involves the knee): never flagged, but not something to
    # add to a session while she rests that area.
    part = ''.join(sorted(CODE[a] for a, v in t['limits'].items() if v == 1))
    if part: touches[i] = part

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'limits-data.js')
js = lambda x: json.dumps(x, ensure_ascii=False, separators=(',', ':'))
with open(out, 'w') as f:
    f.write('// Generated by scripts/fitkat/limits/export.py from the catalogue and the movement ladders. Do not edit by hand.\n')
    f.write('//\n// FLAGS[exerciseId][area] is what an exercise that loads that area is offered: a number is an index into LISTS;\n')
    f.write("// 'e' is no ladder (keep it, easier); 't' is a hold (keep it, for a shorter time); 'x' is jumping, running or an\n")
    f.write("// Olympic lift with a leg limit (skip under Go easy too). Areas: n neck, s shoulder, e elbow, w wrist, b lower back,\n")
    f.write("// h hip, k knee, a ankle. A LISTS entry is the ordered steps: ['r', [[id, why], ...]] a replacement (the first id her\n")
    f.write("// kit allows), ['h', ...] a hold, ['a', why] keep the same exercise, adjusted. `why` indexes WHYS.\n")
    f.write('export const WHYS = ' + js(whys) + '\n')
    f.write('export const LISTS = ' + js(lists) + '\n')
    f.write('export const FLAGS = ' + js(flags) + '\n')
    f.write('// TOUCHES[exerciseId] is the areas an exercise involves without loading them, as a string of area letters.\n')
    f.write('export const TOUCHES = ' + js(touches) + '\n')
    # The readings (readings.json): every strength and body-weight exercise, read one by one by an AI reviewer.
    # "loaded|involved", as area letters. They decide what "told to rest" takes out and asks about, and what may
    # be added to a session. Go easy and Avoid stay on the rules above (owner, 22 Nov).
    readings = json.load(open(os.path.join(HERE, 'readings.json')))
    read = {i: v for i, v in sorted(readings.items()) if i in V.EX and v != '|'}
    f.write('// READ[exerciseId] is an AI reviewer\'s reading of the exercise: the areas it loads, a bar, the areas it only\n')
    f.write('// involves. Used for an area she was told to rest and for what may be added to a session, never for a ladder.\n')
    f.write('export const READ = ' + js(read) + '\n')
    pool = [i for i in json.load(open(os.path.join(HERE, 'fill-pool.json'))) if i in V.EX and i in readings]
    f.write('// POOL is the exercises suggested for "Build your own": about 300 well-known ones.\n')
    f.write('export const POOL = ' + js(pool) + '\n')
print('flagged exercises', len(flags), '| lists', len(lists), '| reasons', len(whys), '| bytes', os.path.getsize(out))
