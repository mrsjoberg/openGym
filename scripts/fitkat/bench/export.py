"""Writes frontend/src/fitkat/needs-data.js: what an exercise needs to sit, lie, lean or step on (needs.json, see README.md).

    python3 scripts/fitkat/bench/export.py            # writes it
    python3 scripts/fitkat/bench/export.py --check    # fails when it is out of date
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', 'frontend', 'src', 'fitkat', 'needs-data.js')
CODE = {'none': 'n', 'chair': 'c', 'flat': 'f', 'incline': 'i', 'box': 'b', 'station': 's'}

def build():
    needs = json.load(open(os.path.join(HERE, 'needs.json')))['needs']
    data = {i: CODE[c] for i, c in sorted(needs.items())}
    return ('// Generated by scripts/fitkat/bench/export.py from scripts/fitkat/bench/needs.json. Do not edit by hand.\n//\n'
            "// NEEDS[exerciseId]: what it needs to sit, lie, lean or step on. 'n' nothing beyond its own kit, 'c' a chair\n"
            "// will do, 'f' a flat bench, 'i' an adjustable bench, 'b' a box or step, 's' other gym furniture.\n"
            'export const NEEDS = ' + json.dumps(data, separators=(',', ':')) + '\n'), len(data)

if __name__ == '__main__':
    text, n = build()
    if '--check' in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text: sys.exit('needs-data.js is out of date: run scripts/fitkat/bench/export.py')
        print('needs-data.js is up to date'); sys.exit(0)
    open(OUT, 'w').write(text)
    print(n, 'exercises |', len(text), 'bytes')
