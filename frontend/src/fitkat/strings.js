/** A FitKat string in the app's language, `{0}` `{1}` filled from the arguments. */
export function ft(s, ...args) {
  let v = (getLang() === 'ru' && RU[s]) || s
  for (let i = 0; i < args.length; i++) v = v.split('{' + i + '}').join(String(args[i]))
  return v
}
